// Writes conformance/results.json and docs/CONFORMANCE.md. Usage: tsx conformance/report.ts redis://127.0.0.1:6379
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { runDifferential } from "./run.js";

const url = process.argv[2] ?? "redis://127.0.0.1:6379";
const { results, byGroup } = await runDifferential(url, { fuzzOps: 2000, seed: 42 });
let version = "unknown";
try { version = execFileSync("redis-server", ["--version"]).toString().match(/v=(\S+)/)?.[1] ?? version; } catch { /* not on PATH */ }
const total = results.length;
const pass = results.filter((r) => r.ok).length;
const summary = { generatedAt: new Date().toISOString(), redisServer: version, total, pass, rate: Number(((pass / total) * 100).toFixed(2)), byGroup, failures: results.filter((r) => !r.ok) };
writeFileSync(new URL("./results.json", import.meta.url), JSON.stringify(summary, null, 2) + "\n");
const rows = Object.entries(byGroup).map(([g, v]) => `| ${g} | ${v.pass} | ${v.total} | ${((v.pass / v.total) * 100).toFixed(1)}% |`).join("\n");
const md = `# Redis differential conformance

Every case runs on the embedded engine and on a real \`redis-server\` (${version}) through the
same RESP client, on a freshly flushed database per group. Replies are normalised (status vs bulk,
errors compared by their first word, unordered set replies sorted) and must be identical.

Generated by \`pnpm --filter edgestash conformance\`. Raw results: \`packages/server/conformance/results.json\`.

| Group | Pass | Total | Rate |
| --- | ---: | ---: | ---: |
${rows}
| **all** | **${pass}** | **${total}** | **${summary.rate}%** |
`;
writeFileSync(new URL("../../../docs/CONFORMANCE.md", import.meta.url), md);
console.log(`${pass}/${total} (${summary.rate}%)`);
